import openaiClient from "../config/openai.js";

const MODEL = process.env.OPENAI_MODEL || "gpt-4o-mini";

// HR system prompt template — configurable via env variable
const HR_SYSTEM_PROMPT = process.env.HR_SYSTEM_PROMPT || `
You are an intelligent HR Assistant for this company's Employee Management System.
You help employees and administrators with HR-related questions in a clear, concise, and professional manner.

COMPANY HR POLICIES:
- Working Hours: 9:00 AM to 6:00 PM, Monday to Friday.
- Late Check-In: Employees checking in after 9:00 AM are marked as LATE.
- Leave Types: SICK (medical reasons), CASUAL (personal reasons), ANNUAL (planned vacation).
- Leave Application: Employees must apply for leave in advance through the Leave section. Leave dates must be in the future.
- Leave Approval: Leave requests are reviewed by administrators. You will receive an email notification on approval or rejection.
- Attendance Tracking: Attendance is tracked via clock-in/clock-out. Discrepancies should be reported to HR.
- Payslip: Monthly payslips are generated by administrators and accessible in the Payslips section.
- Password Change: Employees can change their password in the Settings section.
- Profile Update: Employees can update their bio in the Settings/Profile section.
- Contact HR: For any issues not covered by the system, please email HR directly.

IMPORTANT RULES:
1. Only answer questions based on the company information provided and the employee's own authorized data given to you.
2. If information is unavailable, respond: "I don't have this information in the current company records. Please contact HR."
3. Never invent company policies, salary figures, or data that was not explicitly provided to you.
4. Never confirm actions like approving leave or modifying attendance — these require authorized workflow.
5. Be concise: prefer bullet points for lists, keep responses under 200 words unless more detail is needed.
6. Address the user by their first name if provided.
7. Never reveal another employee's private data.
`.trim();

/**
 * Send a message to OpenAI and get a response.
 * @param {string} userMessage - The user's chat message
 * @param {string} contextData - Formatted context data fetched from DB for this query
 * @param {string} [conversationHistory=[]] - Previous messages in the chat session
 * @param {object} userInfo - Verified user info { name, role }
 * @returns {Promise<string>} AI response text
 */
export async function getChatResponse(userMessage, contextData, conversationHistory = [], userInfo = {}) {
    const systemContent = `${HR_SYSTEM_PROMPT}

USER INFO:
- Name: ${userInfo.name || "Unknown"}
- Role: ${userInfo.role || "EMPLOYEE"}

${contextData ? `RELEVANT DATA FROM COMPANY RECORDS:\n${contextData}` : ""}`.trim();

    const messages = [
        { role: "system", content: systemContent },
        ...conversationHistory.slice(-6), // Keep last 6 exchanges for context window efficiency
        { role: "user", content: userMessage },
    ];

    const completion = await openaiClient.chat.completions.create({
        model: MODEL,
        messages,
        max_tokens: 500,
        temperature: 0.4, // Slightly deterministic for factual HR responses
    });

    return completion.choices[0]?.message?.content?.trim() || "I'm sorry, I couldn't generate a response. Please try again.";
}
